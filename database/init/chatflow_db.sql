-- ChatFlow database
-- PostgreSQL
-- Run this file with: psql -U postgres -f chatflow_db.sql
-- The CREATE DATABASE statement must be executed by a user with CREATEDB privilege.

CREATE DATABASE chatflow_db
    WITH ENCODING = 'UTF8'
         TEMPLATE = template0;

\connect chatflow_db

-- Optional: use a dedicated schema for the application.
CREATE SCHEMA IF NOT EXISTS chatflow;
SET search_path TO chatflow, public;

-- =========================================================
-- 1. UTILISATEUR
-- =========================================================
CREATE TABLE utilisateur (
    id_utilisateur       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_telephone     VARCHAR(20)  NOT NULL UNIQUE,
    mot_de_passe         VARCHAR(255) NOT NULL, -- store a password hash, never plaintext
    pseudo               VARCHAR(50)  NOT NULL UNIQUE,
    nom_affiche          VARCHAR(100),
    photo_profil         VARCHAR(500),
    statut               VARCHAR(20)  NOT NULL DEFAULT 'HORS_LIGNE'
                         CHECK (statut IN ('EN_LIGNE', 'HORS_LIGNE', 'ABSENT', 'OCCUPE')),
    derniere_connexion   TIMESTAMPTZ,
    cree_le              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- =========================================================
-- 2. CONVERSATION
-- =========================================================
CREATE TABLE conversation (
    id_conversation BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nature          VARCHAR(20) NOT NULL
                    CHECK (nature IN ('PRIVEE', 'GROUPE')),
    cree_le         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- =========================================================
-- 3. PARTICIPANT
-- A user can participate in many conversations.
-- A conversation can contain many users.
-- Composite PK prevents duplicate membership.
-- =========================================================
CREATE TABLE participant (
    id_utilisateur       BIGINT NOT NULL,
    id_conversation      BIGINT NOT NULL,
    role                 VARCHAR(20) NOT NULL DEFAULT 'MEMBRE'
                         CHECK (role IN ('ADMIN', 'MEMBRE')),
    date_adhesion        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_derniere_lecture TIMESTAMPTZ,
    date_sortie          TIMESTAMPTZ,
    PRIMARY KEY (id_utilisateur, id_conversation),
    CONSTRAINT fk_participant_utilisateur
        FOREIGN KEY (id_utilisateur) REFERENCES utilisateur(id_utilisateur)
        ON DELETE CASCADE,
    CONSTRAINT fk_participant_conversation
        FOREIGN KEY (id_conversation) REFERENCES conversation(id_conversation)
        ON DELETE CASCADE
);

CREATE INDEX idx_participant_conversation
    ON participant(id_conversation);

-- =========================================================
-- 4. GROUPE
-- One group profile at most per conversation.
-- A conversation of nature PRIVEE must not have a group row;
-- this consistency is enforced by application logic.
-- =========================================================
CREATE TABLE groupe (
    id_groupe       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_conversation BIGINT NOT NULL UNIQUE,
    nom             VARCHAR(100) NOT NULL,
    description     TEXT,
    photo_groupe    VARCHAR(500),
    CONSTRAINT fk_groupe_conversation
        FOREIGN KEY (id_conversation) REFERENCES conversation(id_conversation)
        ON DELETE CASCADE
);

-- =========================================================
-- 5. MESSAGE
-- Recipient(s) are represented by MESSAGE_DESTINATAIRE, not by
-- one id_destinataire column, so group chats are supported.
-- =========================================================
CREATE TABLE message (
    id_message       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_conversation  BIGINT NOT NULL,
    id_expediteur    BIGINT NOT NULL,
    contenu          TEXT,
    type_message     VARCHAR(20) NOT NULL DEFAULT 'TEXTE'
                     CHECK (type_message IN
                         ('TEXTE', 'IMAGE', 'VIDEO', 'AUDIO', 'FICHIER', 'LOCALISATION', 'SYSTEME')),
    envoye_le        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modifie_le       TIMESTAMPTZ,
    statut           VARCHAR(20) NOT NULL DEFAULT 'ENVOYE'
                     CHECK (statut IN ('ENVOYE', 'DISTRIBUE', 'LU', 'ECHEC')),
    supprime_le      TIMESTAMPTZ,
    CONSTRAINT fk_message_conversation
        FOREIGN KEY (id_conversation) REFERENCES conversation(id_conversation)
        ON DELETE CASCADE,
    CONSTRAINT fk_message_expediteur
        FOREIGN KEY (id_expediteur) REFERENCES utilisateur(id_utilisateur)
        ON DELETE RESTRICT,
    CONSTRAINT uq_message_id_conversation UNIQUE (id_message, id_conversation)
);

CREATE INDEX idx_message_conversation_date
    ON message(id_conversation, envoye_le DESC);

CREATE INDEX idx_message_expediteur
    ON message(id_expediteur);

-- =========================================================
-- 6. MESSAGE_DESTINATAIRE
-- One row per recipient per message; useful for group delivery/read
-- receipts. The composite PK prevents duplicate receipts.
-- =========================================================
CREATE TABLE message_destinataire (
    id_message       BIGINT NOT NULL,
    id_utilisateur   BIGINT NOT NULL,
    id_conversation  BIGINT NOT NULL,
    statut_reception VARCHAR(20) NOT NULL DEFAULT 'ENVOYE'
                     CHECK (statut_reception IN ('ENVOYE', 'DISTRIBUE', 'LU', 'ECHEC')),
    date_reception   TIMESTAMPTZ,
    date_lecture     TIMESTAMPTZ,
    PRIMARY KEY (id_message, id_utilisateur),
    CONSTRAINT fk_md_message_conversation
        FOREIGN KEY (id_message, id_conversation)
        REFERENCES message(id_message, id_conversation)
        ON DELETE CASCADE,
    CONSTRAINT fk_md_participant
        FOREIGN KEY (id_utilisateur, id_conversation)
        REFERENCES participant(id_utilisateur, id_conversation)
        ON DELETE CASCADE
);

CREATE INDEX idx_message_destinataire_utilisateur
    ON message_destinataire(id_utilisateur, statut_reception);

-- =========================================================
-- 7. PIECE_JOINTE
-- The actual file is stored on disk/object storage; the DB stores
-- its path and metadata.
-- =========================================================
CREATE TABLE piece_jointe (
    id_piece_jointe BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_message      BIGINT NOT NULL,
    nom_original    VARCHAR(255) NOT NULL,
    chemin_stockage VARCHAR(1000) NOT NULL,
    type_mime       VARCHAR(150),
    taille_octets   BIGINT CHECK (taille_octets IS NULL OR taille_octets >= 0),
    empreinte_sha256 CHAR(64),
    CONSTRAINT fk_piece_jointe_message
        FOREIGN KEY (id_message) REFERENCES message(id_message)
        ON DELETE CASCADE
);

CREATE INDEX idx_piece_jointe_message
    ON piece_jointe(id_message);

-- =========================================================
-- 8. APPEL
-- =========================================================
CREATE TABLE appel (
    id_appel       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_conversation BIGINT NOT NULL,
    id_initiateur  BIGINT NOT NULL,
    type_appel     VARCHAR(20) NOT NULL
                   CHECK (type_appel IN ('AUDIO', 'VIDEO')),
    date_debut     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_fin       TIMESTAMPTZ,
    statut         VARCHAR(20) NOT NULL DEFAULT 'EN_COURS'
                   CHECK (statut IN ('EN_COURS', 'TERMINE', 'MANQUE', 'REFUSE', 'ANNULE')),
    CONSTRAINT fk_appel_conversation
        FOREIGN KEY (id_conversation) REFERENCES conversation(id_conversation)
        ON DELETE CASCADE,
    CONSTRAINT fk_appel_initiateur_participant
        FOREIGN KEY (id_initiateur, id_conversation)
        REFERENCES participant(id_utilisateur, id_conversation)
        ON DELETE RESTRICT,
    CONSTRAINT ck_appel_dates
        CHECK (date_fin IS NULL OR date_fin >= date_debut)
);

CREATE INDEX idx_appel_conversation_date
    ON appel(id_conversation, date_debut DESC);

-- =========================================================
-- 9. APPEL_PARTICIPANT
-- Composite PK: one row for each user in a given call.
-- =========================================================
CREATE TABLE appel_participant (
    id_appel       BIGINT NOT NULL,
    id_utilisateur BIGINT NOT NULL,
    date_entree    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_sortie    TIMESTAMPTZ,
    statut         VARCHAR(20) NOT NULL DEFAULT 'INVITE'
                   CHECK (statut IN ('INVITE', 'ACCEPTE', 'REFUSE', 'MANQUE', 'QUITTЕ')),
    micro_active   BOOLEAN NOT NULL DEFAULT TRUE,
    camera_active  BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (id_appel, id_utilisateur),
    CONSTRAINT fk_ap_appel
        FOREIGN KEY (id_appel) REFERENCES appel(id_appel)
        ON DELETE CASCADE,
    CONSTRAINT fk_ap_utilisateur
        FOREIGN KEY (id_utilisateur) REFERENCES utilisateur(id_utilisateur)
        ON DELETE RESTRICT,
    CONSTRAINT ck_appel_participant_dates
        CHECK (date_sortie IS NULL OR date_sortie >= date_entree)
);

CREATE INDEX idx_appel_participant_utilisateur
    ON appel_participant(id_utilisateur);

-- =========================================================
-- Helpful view: conversation list with last message timestamp
-- =========================================================
CREATE VIEW v_conversations_utilisateur AS
SELECT
    p.id_utilisateur,
    c.id_conversation,
    c.nature,
    c.cree_le,
    MAX(m.envoye_le) AS dernier_message_le
FROM participant p
JOIN conversation c ON c.id_conversation = p.id_conversation
LEFT JOIN message m ON m.id_conversation = c.id_conversation
WHERE p.date_sortie IS NULL
GROUP BY p.id_utilisateur, c.id_conversation, c.nature, c.cree_le;

-- End of ChatFlow schema.
