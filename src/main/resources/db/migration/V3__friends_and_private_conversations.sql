-- Optional social graph: friendship is independent from direct messaging.
CREATE TABLE IF NOT EXISTS chatflow.friend_request (
    id_request BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id BIGINT NOT NULL REFERENCES chatflow.utilisateur(id_utilisateur) ON DELETE CASCADE,
    recipient_id BIGINT NOT NULL REFERENCES chatflow.utilisateur(id_utilisateur) ON DELETE CASCADE,
    user_low BIGINT GENERATED ALWAYS AS (LEAST(requester_id, recipient_id)) STORED,
    user_high BIGINT GENERATED ALWAYS AS (GREATEST(requester_id, recipient_id)) STORED,
    status VARCHAR(12) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','ACCEPTED','REJECTED','CANCELLED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    responded_at TIMESTAMPTZ,
    CHECK (requester_id <> recipient_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_friend_request_pending_pair
    ON chatflow.friend_request(user_low, user_high) WHERE status = 'PENDING';
CREATE INDEX IF NOT EXISTS idx_friend_request_recipient_status
    ON chatflow.friend_request(recipient_id, status, created_at DESC);
CREATE TABLE IF NOT EXISTS chatflow.friendship (
    user_low BIGINT NOT NULL REFERENCES chatflow.utilisateur(id_utilisateur) ON DELETE CASCADE,
    user_high BIGINT NOT NULL REFERENCES chatflow.utilisateur(id_utilisateur) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_low, user_high),
    CHECK (user_low < user_high)
);

-- Canonical user pair prevents duplicate private conversations, even under concurrent requests.
ALTER TABLE chatflow.conversation ADD COLUMN IF NOT EXISTS direct_user_low BIGINT;
ALTER TABLE chatflow.conversation ADD COLUMN IF NOT EXISTS direct_user_high BIGINT;
ALTER TABLE chatflow.conversation ADD COLUMN IF NOT EXISTS derniere_activite TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP;

-- Backfill only unambiguous legacy private conversations (exactly two active members,
-- and only one legacy conversation for that pair).
WITH legacy_pairs AS (
    SELECT c.id_conversation, MIN(p.id_utilisateur) AS user_low, MAX(p.id_utilisateur) AS user_high
    FROM chatflow.conversation c
    JOIN chatflow.participant p ON p.id_conversation = c.id_conversation AND p.date_sortie IS NULL
    WHERE c.nature = 'PRIVEE'
    GROUP BY c.id_conversation
    HAVING COUNT(*) = 2
), unique_pairs AS (
    SELECT user_low, user_high FROM legacy_pairs GROUP BY user_low, user_high HAVING COUNT(*) = 1
)
UPDATE chatflow.conversation c
SET direct_user_low = lp.user_low, direct_user_high = lp.user_high
FROM legacy_pairs lp JOIN unique_pairs up USING (user_low, user_high)
WHERE c.id_conversation = lp.id_conversation;
ALTER TABLE chatflow.conversation ADD CONSTRAINT ck_private_conversation_pair
    CHECK ((nature <> 'PRIVEE') OR
           ((direct_user_low IS NULL AND direct_user_high IS NULL) OR
            (direct_user_low IS NOT NULL AND direct_user_high IS NOT NULL AND direct_user_low < direct_user_high))) NOT VALID;
CREATE UNIQUE INDEX IF NOT EXISTS uq_conversation_private_pair
    ON chatflow.conversation(direct_user_low, direct_user_high)
    WHERE nature = 'PRIVEE' AND direct_user_low IS NOT NULL AND direct_user_high IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_conversation_activity ON chatflow.conversation(derniere_activite DESC);
ALTER TABLE chatflow.conversation ADD CONSTRAINT fk_conversation_direct_low
    FOREIGN KEY (direct_user_low) REFERENCES chatflow.utilisateur(id_utilisateur) ON DELETE CASCADE NOT VALID;
ALTER TABLE chatflow.conversation ADD CONSTRAINT fk_conversation_direct_high
    FOREIGN KEY (direct_user_high) REFERENCES chatflow.utilisateur(id_utilisateur) ON DELETE CASCADE NOT VALID;
UPDATE chatflow.conversation c
SET derniere_activite = COALESCE(
    (SELECT MAX(m.envoye_le) FROM chatflow.message m WHERE m.id_conversation = c.id_conversation),
    c.cree_le
);
