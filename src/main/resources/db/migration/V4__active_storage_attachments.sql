-- Rails Active Storage-inspired disk storage metadata.
-- Binary files stay on the application filesystem; PostgreSQL stores metadata and associations.
CREATE TABLE IF NOT EXISTS chatflow.active_storage_blobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key VARCHAR(64) NOT NULL UNIQUE,
    filename VARCHAR(255) NOT NULL,
    content_type VARCHAR(255) NOT NULL,
    byte_size BIGINT NOT NULL CHECK (byte_size >= 0),
    checksum VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS chatflow.active_storage_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL DEFAULT 'file',
    record_type VARCHAR(100) NOT NULL DEFAULT 'Message',
    record_id BIGINT NOT NULL REFERENCES chatflow.message(id_message) ON DELETE CASCADE,
    blob_id BIGINT NOT NULL REFERENCES chatflow.active_storage_blobs(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_active_storage_attachment UNIQUE (record_type, record_id, name, blob_id)
);

CREATE INDEX IF NOT EXISTS idx_active_storage_attachments_blob
    ON chatflow.active_storage_attachments(blob_id);
CREATE INDEX IF NOT EXISTS idx_active_storage_attachments_record
    ON chatflow.active_storage_attachments(record_type, record_id);
