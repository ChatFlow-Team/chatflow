CREATE SCHEMA IF NOT EXISTS chatflow;

CREATE TABLE IF NOT EXISTS chatflow.utilisateur (
    id_utilisateur BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_telephone VARCHAR(24) NOT NULL UNIQUE,
    mot_de_passe VARCHAR(255) NOT NULL,
    pseudo VARCHAR(32) NOT NULL UNIQUE,
    nom_affiche VARCHAR(80) NOT NULL,
    photo_profil TEXT,
    statut VARCHAR(16) NOT NULL DEFAULT 'HORS_LIGNE'
        CHECK (statut IN ('EN_LIGNE', 'HORS_LIGNE', 'ABSENT', 'OCCUPE')),
    derniere_connexion TIMESTAMPTZ,
    cree_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS chatflow.conversation (
    id_conversation BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nature VARCHAR(12) NOT NULL CHECK (nature IN ('PRIVEE', 'GROUPE')),
    cree_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS chatflow.participant (
    id_utilisateur BIGINT NOT NULL REFERENCES chatflow.utilisateur(id_utilisateur) ON DELETE CASCADE,
    id_conversation BIGINT NOT NULL REFERENCES chatflow.conversation(id_conversation) ON DELETE CASCADE,
    role VARCHAR(12) NOT NULL DEFAULT 'MEMBRE' CHECK (role IN ('MEMBRE', 'ADMIN')),
    date_adhesion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_sortie TIMESTAMPTZ,
    PRIMARY KEY (id_utilisateur, id_conversation)
);

CREATE TABLE IF NOT EXISTS chatflow.message (
    id_message BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_conversation BIGINT NOT NULL,
    id_expediteur BIGINT NOT NULL,
    contenu TEXT,
    type_message VARCHAR(12) NOT NULL DEFAULT 'TEXTE'
        CHECK (type_message IN ('TEXTE', 'IMAGE', 'VIDEO', 'AUDIO', 'FICHIER', 'SYSTEME')),
    envoye_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modifie_le TIMESTAMPTZ,
    supprime_le TIMESTAMPTZ,
    CONSTRAINT fk_message_expediteur_participant
        FOREIGN KEY (id_expediteur, id_conversation)
        REFERENCES chatflow.participant(id_utilisateur, id_conversation) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS chatflow.message_destinataire (
    id_message BIGINT NOT NULL REFERENCES chatflow.message(id_message) ON DELETE CASCADE,
    id_destinataire BIGINT NOT NULL REFERENCES chatflow.utilisateur(id_utilisateur) ON DELETE CASCADE,
    statut VARCHAR(12) NOT NULL DEFAULT 'ENVOYE'
        CHECK (statut IN ('ENVOYE', 'RECU', 'LU')),
    recu_le TIMESTAMPTZ,
    lu_le TIMESTAMPTZ,
    PRIMARY KEY (id_message, id_destinataire)
);

CREATE INDEX IF NOT EXISTS idx_participant_conversation_active
    ON chatflow.participant(id_conversation) WHERE date_sortie IS NULL;
CREATE INDEX IF NOT EXISTS idx_message_conversation_date
    ON chatflow.message(id_conversation, envoye_le DESC);
CREATE INDEX IF NOT EXISTS idx_message_destinataire_user_status
    ON chatflow.message_destinataire(id_destinataire, statut);
